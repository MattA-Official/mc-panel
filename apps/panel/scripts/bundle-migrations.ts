// Turns drizzle-kit's SQL files into a TypeScript module, so migrations ship inside the
// Nitro bundle with no files to copy. Run via `bun run db:generate`.
const dir = new URL('../server/db/migrations/', import.meta.url)
const journal = (await Bun.file(new URL('meta/_journal.json', dir)).json()) as {
  entries: { tag: string }[]
}
const migrations = await Promise.all(
  journal.entries.map(async ({ tag }) => ({
    tag,
    sql: await Bun.file(new URL(`${tag}.sql`, dir)).text(),
  })),
)
const out = `// Generated by scripts/bundle-migrations.ts. Do not edit.\nexport const migrations: { tag: string; sql: string }[] = ${JSON.stringify(migrations, null, 2)}\n`
await Bun.write(new URL('../server/db/migrations.gen.ts', import.meta.url), out)
console.log(`bundled ${migrations.length} migration(s)`)
